"""Generate trace.c: a libEGL.so.1 that exports every EGL + GLES2 entry point,
counts calls, logs EGL calls with their attribute lists, and forwards to the
real driver (path in $MGL_REAL_EGL / $MGL_REAL_GLES).
usage: gen_trace.py egl.h eglext.h gl2.h gl2ext.h > trace.c"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from parse import parse

funcs = parse(sys.argv[1:])
o = []
w = o.append
w("""/* generated by gen_trace.py - do not edit */
#define _GNU_SOURCE
#include <EGL/egl.h>
#include <EGL/eglext.h>
#include <GLES2/gl2.h>
#include <GLES2/gl2ext.h>
#include <dlfcn.h>
#include <pthread.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>

#ifndef MGL_DEFAULT_REAL_EGL
#define MGL_DEFAULT_REAL_EGL "/usr/lib/x86_64-linux-gnu/libEGL_real.so.1"
#define MGL_DEFAULT_REAL_GLES "/usr/lib/x86_64-linux-gnu/libGLESv2.so.2"
#define MGL_DEFAULT_TRACE_DIR "/tmp"
#endif
#define NFUNCS %d
static unsigned long mgl_counts[NFUNCS];
static const char *mgl_names[NFUNCS];
static void *real_egl, *real_gles;
static __eglMustCastToProperFunctionPointerType (*real_gpa)(const char *);
static FILE *logf;

static void lib_init(void) {
\tif (real_egl) return;
\tconst char *e = getenv("MGL_REAL_EGL"), *g = getenv("MGL_REAL_GLES");
\treal_egl = dlopen(e ? e : MGL_DEFAULT_REAL_EGL, RTLD_NOW | RTLD_GLOBAL);
\treal_gles = dlopen(g ? g : MGL_DEFAULT_REAL_GLES, RTLD_NOW | RTLD_GLOBAL);
\treal_gpa = (__eglMustCastToProperFunctionPointerType(*)(const char *))dlsym(real_egl, "eglGetProcAddress");
\tchar path[256];
\tsnprintf(path, sizeof path, "%%s/mgltrace-%%d.log", getenv("MGL_TRACE_DIR") ? getenv("MGL_TRACE_DIR") : MGL_DEFAULT_TRACE_DIR, getpid());
\tlogf = fopen(path, "w");
\tif (logf) setvbuf(logf, NULL, _IOLBF, 0);
}
static void *resolve(const char *name, int egl) {
\tlib_init();
\tvoid *p = dlsym(egl ? real_egl : real_gles, name);
\tif (!p && real_gpa) p = (void *)real_gpa(name);
\tif (!p && logf) fprintf(logf, "MISSING real %%s\\n", name);
\treturn p;
}
static void log_attribs(const char *what, const EGLint *a) {
\tif (!logf) return;
\tfprintf(logf, "    %%s:", what);
\tfor (int i = 0; a && a[i] != EGL_NONE && i < 64; i += 2) fprintf(logf, " 0x%%x=0x%%x", a[i], a[i + 1]);
\tfprintf(logf, "\\n");
}
static void log_attribs64(const char *what, const EGLAttrib *a) {
\tif (!logf) return;
\tfprintf(logf, "    %%s:", what);
\tfor (int i = 0; a && a[i] != EGL_NONE && i < 64; i += 2) fprintf(logf, " 0x%%lx=0x%%lx", (long)a[i], (long)a[i + 1]);
\tfprintf(logf, "\\n");
}
static void dump_counts(void) {
\tif (!logf) return;
\tfprintf(logf, "== call counts\\n");
\tfor (int i = 0; i < NFUNCS; i++)
\t\tif (mgl_counts[i]) fprintf(logf, "%%10lu %%s\\n", mgl_counts[i], mgl_names[i]);
\tfflush(logf);
}
__attribute__((destructor)) static void at_exit(void) { dump_counts(); }
""" % len(funcs))

for i, f in enumerate(funcs):
    n, ret = f["name"], f["ret"]
    params = ", ".join(f"{t} {p}" for t, p in f["params"]) or "void"
    args = ", ".join(p for _, p in f["params"])
    egl = 1 if f["api"] == "egl" else 0
    w(f"typedef {ret} (*PFN_{n}_t)({params});")
    w(f"static PFN_{n}_t real_{n};")
    if n == "eglGetProcAddress":
        continue  # hand-written below
    w(f"{ret} {n}({params}) {{")
    w(f"\tmgl_names[{i}] = \"{n}\"; if (__atomic_fetch_add(&mgl_counts[{i}], 1, __ATOMIC_RELAXED) == 0 && logf) fprintf(logf, \"FIRST {n}\\n\");")
    w(f"\tif (!real_{n}) real_{n} = (PFN_{n}_t)resolve(\"{n}\", {egl});")
    if egl:
        w(f"\tif (logf) fprintf(logf, \"{n}\\n\");")
        for t, p in f["params"]:
            if "EGLint *" in t and "attrib" in p.lower() and t.startswith("const"):
                w(f"\tlog_attribs(\"{p}\", {p});")
            if "EGLAttrib *" in t and t.startswith("const"):
                w(f"\tlog_attribs64(\"{p}\", {p});")
            if t in ("EGLenum", "EGLint") and p in ("platform", "name", "attribute", "api"):
                w(f"\tif (logf) fprintf(logf, \"    {p}=0x%x\\n\", (unsigned){p});")
    if n == "eglSwapBuffers":
        w(f"\tif (mgl_counts[{i}] % 50 == 0) dump_counts();")
    if ret == "void":
        w(f"\treal_{n}({args});")
    else:
        w(f"\t{ret} r = real_{n}({args});")
        if n == "eglQueryString":
            w("\tif (logf) fprintf(logf, \"    -> %s\\n\", r ? r : \"(null)\");")
        w("\treturn r;")
    w("}")

# eglGetProcAddress: return our wrappers so every call stays traced.
w("static const struct { const char *n; void *p; } table[] = {")
for f in funcs:
    if f["name"] != "eglGetProcAddress":
        w(f"\t{{\"{f['name']}\", (void *){f['name']}}},")
w("};")
w("""__eglMustCastToProperFunctionPointerType eglGetProcAddress(const char *procname) {
\tlib_init();
\tfor (size_t i = 0; i < sizeof table / sizeof table[0]; i++)
\t\tif (!strcmp(table[i].n, procname)) return (__eglMustCastToProperFunctionPointerType)table[i].p;
\tif (logf) fprintf(logf, "UNKNOWN proc %s\\n", procname);
\treturn real_gpa ? real_gpa(procname) : NULL;
}""")
print("\n".join(o))
